using System.Security.Claims;
using System.Text;
using AsistenteAyuntamiento.Application.Common.Interfaces;
using AsistenteAyuntamiento.Application.Features.Chat;
using Microsoft.SemanticKernel.ChatCompletion;

namespace AsistenteAyuntamiento.ApiService.Features.Query;

/// <summary>Question for <c>POST /api/v1/query</c>.</summary>
/// <param name="Question">The question, in Spanish, about the official bulletins (BOE, BOJA).</param>
public sealed record QueryRequest(string Question);

/// <summary>
/// Answer of <c>POST /api/v1/query</c>. The text ends with the cited official sources, as in the chat.
/// It is generated by an AI model and must be checked against the cited sources.
/// </summary>
public sealed record QueryResponse(string Answer, bool AiGenerated);

/// <summary>
/// Stateless REST entry point to the RAG pipeline for integrations: same pipeline and tenant model as the chat hub,
/// but no session is stored. The chat UI keeps using SignalR (<c>/hubs/chat</c>).
/// </summary>
public static class QueryEndpoints
{
    public const int MaxQuestionLength = 2000;

    public static void MapQueryEndpoints(this IEndpointRouteBuilder app)
    {
        app.MapPost("/api/v1/query", async (
                QueryRequest request,
                ClaimsPrincipal user,
                ICurrentTenantService tenantService,
                IAiChatService aiChatService,
                CancellationToken cancellationToken) =>
            {
                var userId = user.FindFirst(ClaimTypes.NameIdentifier)?.Value;
                var tenantId = tenantService.TenantId;
                if (string.IsNullOrEmpty(userId) || string.IsNullOrEmpty(tenantId))
                {
                    return Results.Unauthorized();
                }

                var question = request.Question?.Trim();
                if (string.IsNullOrEmpty(question) || question.Length > MaxQuestionLength)
                {
                    return Results.ValidationProblem(new Dictionary<string, string[]>
                    {
                        [nameof(QueryRequest.Question)] = [$"The question is required and has at most {MaxQuestionLength} characters."],
                    });
                }

                var history = new ChatHistory();
                history.AddUserMessage(question);

                var answer = new StringBuilder();
                await foreach (var chunk in aiChatService.GetStreamingCompletionAsync(history, tenantId, userId, cancellationToken))
                {
                    answer.Append(chunk);
                }

                return Results.Ok(new QueryResponse(answer.ToString(), AiGenerated: true));
            })
            .RequireAuthorization()
            .WithTags("Query")
            .WithName("Query")
            .WithSummary("Answers a question with the RAG pipeline used by the chat")
            .WithDescription("Stateless: nothing is stored in the chat history. The answer cites the official bulletins it is based on and is AI-generated.")
            .Produces<QueryResponse>()
            .ProducesValidationProblem()
            .Produces(StatusCodes.Status401Unauthorized)
            .Produces(StatusCodes.Status403Forbidden);
    }
}
