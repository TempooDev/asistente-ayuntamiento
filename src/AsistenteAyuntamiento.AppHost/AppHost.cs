var builder = DistributedApplication.CreateBuilder(args);

// ── Auth0 secrets ─────────────────────────────────────────────────────────────
// Stored in user-secrets on AppHost (dev) or an external secrets store (prod).
// dotnet user-secrets set "Parameters:auth0-domain"         "..." --project src/AsistenteAyuntamiento.AppHost
// dotnet user-secrets set "Parameters:auth0-client-id"      "..." --project src/AsistenteAyuntamiento.AppHost
// dotnet user-secrets set "Parameters:auth0-client-secret"  "..." --project src/AsistenteAyuntamiento.AppHost
var auth0Domain = builder.AddParameter("auth0-domain", secret: false);
var auth0ClientId = builder.AddParameter("auth0-client-id", secret: false);
var auth0ClientSecret = builder.AddParameter("auth0-client-secret", secret: true);

// ── AI configuration ─────────────────────────────────────────────────────────
// Local runs use the Ollama container (llama3.2 + nomic-embed-text) so development spends no provider tokens.
// To use the cloud provider from the ai-* parameters (user-secrets) locally:
// dotnet user-secrets set "Ai:UseCloud" "true" --project src/AsistenteAyuntamiento.AppHost
// Publishing always uses the parameters.
var useCloudAi = !builder.ExecutionContext.IsRunMode || string.Equals(builder.Configuration["Ai:UseCloud"], "true", StringComparison.OrdinalIgnoreCase);

void WithAi(IResourceBuilder<IResourceWithEnvironment> resource)
{
    if (!useCloudAi)
    {
        resource.WithEnvironment("Ai__Chat__Provider", "ollama")
                .WithEnvironment("Ai__Chat__Model", "llama3.2")
                .WithEnvironment("Ai__Embeddings__Provider", "ollama")
                .WithEnvironment("Ai__Embeddings__Model", "nomic-embed-text");
        return;
    }

    resource.WithEnvironment("Ai__Chat__Provider", AiParameter("ai-chat-provider", secret: false))
            .WithEnvironment("Ai__Chat__Model", AiParameter("ai-chat-model", secret: false))
            .WithEnvironment("Ai__Chat__ApiKey", AiParameter("ai-chat-api-key", secret: true))
            .WithEnvironment("Ai__Embeddings__Provider", AiParameter("ai-embeddings-provider", secret: false))
            .WithEnvironment("Ai__Embeddings__Model", AiParameter("ai-embeddings-model", secret: false))
            .WithEnvironment("Ai__Embeddings__ApiKey", AiParameter("ai-embeddings-api-key", secret: true));
}

// Declared only when used, so a local Ollama run does not ask for them.
var aiParameters = new Dictionary<string, IResourceBuilder<ParameterResource>>();
IResourceBuilder<ParameterResource> AiParameter(string name, bool secret)
{
    if (!aiParameters.TryGetValue(name, out var parameter))
    {
        parameter = builder.AddParameter(name, secret: secret);
        aiParameters[name] = parameter;
    }
    return parameter;
}

// ── Cloudflare R2 secrets (Optional) ────────────────────────────────────────
// To use R2, set these in user-secrets or appsettings.json instead of parameters.
// If missing, the local MinIO container below is used.
var blobEndpoint = builder.Configuration["Blob:Endpoint"];
var blobAccessKeyId = builder.Configuration["Blob:AccessKeyId"];
var blobSecretAccessKey = builder.Configuration["Blob:SecretAccessKey"];
var blobBucketName = builder.Configuration["Blob:BucketName"] ?? AsistenteAyuntamiento.Shared.AppConstants.BlobStorage.DefaultBucketName;

// ── Local secrets generated by Aspire (persisted in user-secrets, never hardcoded) ─────
var minioUser = builder.AddParameter("minio-root-user", new GenerateParameterDefault { MinLength = 12, Special = false, Upper = false }, persist: true);
var minioPassword = builder.AddParameter("minio-root-password", new GenerateParameterDefault { MinLength = 24, Special = false }, secret: true, persist: true);
// Shared secret the Go scraper sends to the API's internal gRPC FilterConfigService.
var internalGrpcKey = builder.AddParameter("internal-grpc-key", new GenerateParameterDefault { MinLength = 32, Special = false }, secret: true, persist: true);

// Configure MinIO container
// Persistent MinIO Object Storage
var minio = builder.AddContainer("minio", "minio/minio")
    .WithArgs("server", "/data", "--console-address", ":9001")
    .WithVolume("minio-data", "/data")
    .WithHttpEndpoint(port: 9000, targetPort: 9000, name: "api")
    .WithHttpEndpoint(port: 9001, targetPort: 9001, name: "console")
    .WithEnvironment("MINIO_ROOT_USER", minioUser)
    .WithEnvironment("MINIO_ROOT_PASSWORD", minioPassword);

var minioEndpoint = minio.GetEndpoint("api");

// No init container: the ApiService creates the bucket on startup (IBlobStorage.EnsureContainerAsync), and the
// scraper, the only writer, waits for the ApiService.

// Blob credentials: R2 values from configuration when set, otherwise the local MinIO ones.
void WithBlobStorage(IResourceBuilder<IResourceWithEnvironment> resource)
{
    resource.WithEnvironment("Blob__BucketName", blobBucketName);

    if (!string.IsNullOrEmpty(blobEndpoint))
    {
        resource.WithEnvironment("Blob__Endpoint", blobEndpoint)
                .WithEnvironment("Blob__AccessKeyId", blobAccessKeyId)
                .WithEnvironment("Blob__SecretAccessKey", blobSecretAccessKey);
    }
    else
    {
        resource.WithEnvironment("Blob__Endpoint", minioEndpoint)
                .WithEnvironment("Blob__AccessKeyId", minioUser)
                .WithEnvironment("Blob__SecretAccessKey", minioPassword);
    }
}

var auth0Audience = builder.AddParameter("auth0-audience", secret: false);

var postgresServer = builder.AddPostgres("postgres", port: 5432)
    .WithImage("pgvector/pgvector")
    .WithImageTag("pg16")
    .WithDataVolume("asistente-ayuntamiento-pgdata-v2")
    .WithLifetime(ContainerLifetime.Persistent);

var db = postgresServer.AddDatabase("asistente-ayuntamiento-db");

var rabbitmq = builder.AddRabbitMQ("messaging")
    .WithDataVolume("asistente-ayuntamiento-rmqdata")
    .WithLifetime(ContainerLifetime.Persistent);

var qdrant = builder.AddQdrant("qdrant")
    .WithDataVolume("asistente-ayuntamiento-qdrantdata")
    .WithLifetime(ContainerLifetime.Persistent);

var ollama = builder.AddOllama("ollama")
    .WithDataVolume()
    // Ollama's default 4,096-token window drops a system prompt that does not fit (documents included) without
    // an error; the hierarchical answer sends up to ~6,500 tokens of legal text (Ai:Hierarchical:MaxContextChars).
    .WithEnvironment("OLLAMA_CONTEXT_LENGTH", "16384");
// On CPU, local ingestion calls time out. With an NVIDIA GPU visible to the container runtime (Docker, or Podman
// with the NVIDIA Container Toolkit and its CDI spec):
// dotnet user-secrets set "Ollama:Gpu" "true" --project src/AsistenteAyuntamiento.AppHost
if (string.Equals(builder.Configuration["Ollama:Gpu"], "true", StringComparison.OrdinalIgnoreCase))
{
    ollama.WithGPUSupport();
}
ollama.AddModel("llama3.2");
ollama.AddModel("nomic-embed-text");

var apiService = builder.AddProject<Projects.AsistenteAyuntamiento_ApiService>("apiservice")
    .WithReference(ollama)
    .WithHttpHealthCheck("/health")
    .WithReference(db)
    .WithReference(rabbitmq)
    .WithReference(qdrant)
    .WaitFor(db)
    .WaitFor(rabbitmq)
    .WaitFor(qdrant)
    .WithEnvironment("Auth0__Domain", auth0Domain)
    .WithEnvironment("Auth0__ClientId", auth0ClientId)
    .WithEnvironment("Auth0__ClientSecret", auth0ClientSecret)
    .WithEnvironment("Auth0__Audience", auth0Audience);

WithAi(apiService);
WithBlobStorage(apiService);
if (string.IsNullOrEmpty(blobEndpoint))
{
    // The ApiService creates the local bucket on startup, so MinIO must be up first.
    apiService.WaitFor(minio);
}
apiService.WithEnvironment("Internal__GrpcApiKey", internalGrpcKey);

var webfrontend = builder.AddJavaScriptApp("webfrontend", "../AsistenteAyuntamiento.Angular", "start")
    .WithHttpEndpoint(port: 4200, targetPort: 4201, env: "PORT")
    .WithExternalHttpEndpoints()
    .WithReference(apiService)
    .WaitFor(apiService)
    // Auth0 — injected as environment variables (Angular native NG_APP_ format)
    .WithEnvironment("NG_APP_AUTH0_DOMAIN", auth0Domain)
    .WithEnvironment("NG_APP_AUTH0_CLIENT_ID", auth0ClientId)
    .WithEnvironment("NG_APP_AUTH0_AUDIENCE", auth0Audience);

// The SPA is served as static files: it gets no database or storage credentials.

var gateway = builder.AddProject<Projects.AsistenteAyuntamiento_Gateway>("gateway")
    .WithExternalHttpEndpoints()
    .WithReference(apiService)
    .WaitFor(apiService)
    .WaitFor(webfrontend)
    .WithReference(webfrontend);

// No mod tidy / mod vendor on start: they rewrite go.mod, go.sum and vendor/ while go vet and go run read them
// (go vet failed on missing vendor files). Dependencies come from the module cache (mod download).
var goScraper = builder.AddGoApp("go-scraper", "../go-scraper", "./cmd/scraper")
    .WithModDownload()
    .WithVetTool()
    .WithHttpEndpoint(targetPort: 8080, name: "http", env: "PORT")
    .WithHttpEndpoint(targetPort: 50051, name: "grpc", env: "GRPC_PORT")
    .WithHttpHealthCheck("/health")
    .WithReference(rabbitmq)
    .WithReference(apiService)
    .WithEnvironment("DOTNET_API_GRPC_URL", apiService.GetEndpoint("https"))
    .WaitFor(rabbitmq)
    .WaitFor(apiService);

WithBlobStorage(goScraper);
goScraper.WithEnvironment("INTERNAL_GRPC_KEY", internalGrpcKey);

apiService.WithEnvironment("GoScraper__GrpcUrl", goScraper.GetEndpoint("grpc"));

var workerBaseline = builder.AddProject<Projects.AsistenteAyuntamiento_Worker>("worker-baseline")
    // Health endpoints only; each replica gets its own port.
    .WithHttpEndpoint()
    .WithHttpHealthCheck("/health")
    .WithReference(db)
    .WithReference(rabbitmq)
    .WithReference(ollama)
    .WithReference(qdrant)
    .WaitFor(db)
    .WaitFor(rabbitmq)
    .WaitFor(ollama)
    .WaitFor(qdrant)
    .WithEnvironment("WORKER_PIPELINE_MODE", "BASELINE");

WithAi(workerBaseline);
WithBlobStorage(workerBaseline);

var workerHierarchical = builder.AddProject<Projects.AsistenteAyuntamiento_Worker>("worker-hierarchical")
    // Health endpoints only; each replica gets its own port.
    .WithHttpEndpoint()
    .WithHttpHealthCheck("/health")
    .WithReference(db)
    .WithReference(rabbitmq)
    .WithReference(ollama)
    .WithReference(qdrant)
    .WaitFor(db)
    .WaitFor(rabbitmq)
    .WaitFor(ollama)
    .WaitFor(qdrant)
    .WithEnvironment("WORKER_PIPELINE_MODE", "HIERARCHICAL");

WithAi(workerHierarchical);
WithBlobStorage(workerHierarchical);

builder.Build().Run();

